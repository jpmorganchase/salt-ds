"""Regenerate vector lettering with fonttools==4.61.1 and skia-pathops==0.9.2. No runtime font dependency.
Usage: python generate-letterforms.py /path/to/Roboto.ttf
Source: https://raw.githubusercontent.com/google/fonts/main/ofl/roboto/Roboto%5Bwdth,wght%5D.ttf
The SHA-256 guard pins the reviewed font even if the upstream URL changes.
"""
from pathlib import Path
import hashlib, json, sys
from fontTools.ttLib import TTFont
from fontTools.ttLib.removeOverlaps import removeOverlaps
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path
import pathops

source = Path(sys.argv[1])
expected = "d7598e12c5dbef095ff8272cfc55da0250bd07fbdecbac8a530b9b277872a134"
if hashlib.sha256(source.read_bytes()).hexdigest() != expected:
    raise ValueError("Font differs from the reviewed Roboto v3.015 source")

def glyphs(weight, characters):
    font = instantiateVariableFont(TTFont(source), {"wght": weight, "wdth": 100}, inplace=True)
    # Variable masters can overlap. Union them before SVG even-odd filling
    # and outlining, so overlaps cannot become holes or internal strokes.
    removeOverlaps(font)
    substitutions = {}
    gsub = font['GSUB'].table
    for feature in gsub.FeatureList.FeatureRecord:
        if feature.FeatureTag == 'pnum':
            for index in feature.Feature.LookupListIndex:
                for subtable in gsub.LookupList.Lookup[index].SubTable:
                    if not hasattr(subtable, 'mapping'):
                        raise ValueError('Unsupported proportional numeral substitution')
                    substitutions.update(subtable.mapping)
    cap = font['OS/2'].sCapHeight
    scale = 7 / cap
    transform = (scale, 0, 0, -scale, 0, 7)
    cmap, outlines = font.getBestCmap(), font.getGlyphSet()
    output = {}
    for character in characters:
        name = substitutions.get(cmap[ord(character)], cmap[ord(character)])
        glyph = outlines[name]
        path = SVGPathPen(outlines, ntos=lambda n: str(round(n, 4)).rstrip('0').rstrip('.') if '.' in str(round(n, 4)) else str(round(n, 4)))
        bounds = BoundsPen(outlines)
        glyph.draw(TransformPen(path, transform))
        glyph.draw(TransformPen(bounds, transform))
        output[character] = {'d': path.getCommands(), 'advance': round(glyph.width * scale, 4), 'bounds': [round(n, 4) for n in bounds.bounds]}
    return output

regular = glyphs(400, '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabc')
bold = glyphs(700, 'B')
tracking = 1
header = '''// Roboto v3.015 vector outlines, regular 400 and bold 700; width 100.
// Proportional lining numerals (pnum); seven-unit capital-height metric.
// Copyright 2011 The Roboto Project Authors. SIL OFL 1.1.
// See ROBOTO-LICENSE.txt and generate-letterforms.py for source and regeneration.
// Generated data only: icons load no font at runtime.
'''
Path(__file__).with_name('letterforms.mjs').write_text(header + 'export const regularLetterforms = ' + json.dumps(regular, indent=2) + ';\nexport const letterTracking = ' + str(tracking) + ';\nexport const boldLetterforms = ' + json.dumps(bold, indent=2) + ';\n', encoding='utf8')
print('Generated Roboto glyphs:', len(regular) + len(bold))

# The caption symbol shares Roboto C contours in positive and inverse paint.
# Expand locally for native-size recognition, then subtract the real slash
# clearance geometrically. Generated paths retain curves, not raster traces.
c = pathops.Path()
parse_path(regular['C']['d'], c.getPen())
edge = pathops.Path(c)
edge.stroke(0.55, pathops.LineCap.BUTT_CAP, pathops.LineJoin.ROUND_JOIN, 4)
edge.convertConicsToQuads(0.001)
c = pathops.op(c, edge, pathops.PathOp.UNION)
x0, y0, x1, y1 = c.bounds
caption = pathops.Path()
# Use the same advance and tracking as textLabel, then center visible ink.
caption_advance = regular['C']['advance'] + tracking
for center in [12 - caption_advance/2, 12 + caption_advance/2]:
    positioned = c.transform(1, 0, 0, 1, center - (x0+x1)/2, 12 - (y0+y1)/2)
    caption = pathops.op(caption, positioned, pathops.PathOp.UNION)
buffer = 1.4 * 2**0.5
slash = pathops.Path()
slash.moveTo(-30, -30-buffer)
slash.lineTo(40, 40-buffer)
slash.lineTo(40, 40+buffer)
slash.lineTo(-30, -30+buffer)
slash.close()
disabled = pathops.op(caption, slash, pathops.PathOp.DIFFERENCE)
def svg(path):
    pen = SVGPathPen(None, ntos=lambda n: format(n, '.5f').rstrip('0').rstrip('.'))
    path.draw(pen)
    return pen.getCommands()
Path(__file__).with_name('caption-letterforms.mjs').write_text(
    '// Roboto C, optically expanded and clipped for the caption symbol.\n'
    '// Generated by generate-letterforms.py; see ROBOTO-LICENSE.txt.\n'
    + 'export const captionHole = ' + json.dumps(svg(caption)) + ';\n'
    + 'export const disabledCaptionHole = ' + json.dumps(svg(disabled)) + ';\n', encoding='utf8')
