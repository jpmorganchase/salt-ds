// Generates src/css/experimental/rem-units.css from the theme's px tokens.
// Run `yarn workspace @salt-ds/theme generate:rem-units` after changing them.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
export const cssDir = path.join(scriptDir, "../src/css");
export const outputPath = path.join(cssDir, "experimental/rem-units.css");

export const SOURCES = [
  ["foundations/size.css", "Size (all themes)"],
  ["foundations/spacing.css", "Spacing (all themes)"],
  ["legacy/characteristics/text.css", "Text: legacy (UITK) theme"],
  ["next/characteristics/text.css", "Text: J.P. Morgan (theme-next)"],
  ["salt-interim/characteristics/text.css", "Text: J.P. Morgan (Interim)"],
  ["deprecated/characteristics.css", "Deprecated text"],
  ["deprecated/foundations.css", "Deprecated size"],
];

const TEXT_TOKEN =
  /^--salt-(?:text(?:-[\w-]+)?|accent|actionable)-(?:fontSize|lineHeight|minHeight|letterSpacing)$/;
const SIZE_TOKEN = /^--salt-(?:size|spacing|icon-size)-/;
// Hairlines stay in px so they remain crisp at any text size.
const HAIRLINE_TOKEN = /fixed|border|strokeWidth/i;
const PX_VALUE = /^(-?\d*\.?\d+)px$/;

export const isConvertedToken = (name) =>
  TEXT_TOKEN.test(name) ||
  (SIZE_TOKEN.test(name) && !HAIRLINE_TOKEN.test(name));

const toRem = (px) => (px === 0 ? "0" : `${+(px / 16).toFixed(6)}rem`);

const countClasses = (selector) => (selector.match(/\./g) ?? []).length;

// One more class than the source rule, so the override wins regardless of
// import order. Mobile rules already at the specificity of mobile-interim.css
// are kept, so that file still wins when imported after this one.
const overrideSelector = (selector) =>
  selector.includes(".salt-density-mobile") && countClasses(selector) >= 2
    ? selector
    : `.salt-theme${selector}`;

/**
 * Returns each rule's selectors and its custom property declarations, with
 * blank strings marking the blank lines that group them.
 */
export function parseRules(css) {
  const rules = [];
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, "");
  for (const [, selectorText, body] of withoutComments.matchAll(
    /([^{}]+)\{([^{}]*)\}/g,
  )) {
    const lines = [];
    for (const rawLine of body.split("\n")) {
      const match = rawLine.trim().match(/^(--[\w-]+):\s*(.+?);?$/);
      lines.push(match ? { name: match[1], value: match[2] } : "");
    }
    const selectors = selectorText
      .split(",")
      .map((selector) => selector.trim())
      .filter(Boolean);
    rules.push({ selectors, lines });
  }
  return rules;
}

/** Tokens that have a px value in a source rule and are converted to rem. */
export function convertedTokenNames(sourceDir = cssDir) {
  const names = new Set();
  for (const [file] of SOURCES) {
    const css = fs.readFileSync(path.join(sourceDir, file), "utf8");
    for (const { lines } of parseRules(css)) {
      for (const line of lines) {
        if (line && PX_VALUE.test(line.value) && isConvertedToken(line.name)) {
          names.add(line.name);
        }
      }
    }
  }
  return names;
}

// Every declaration of a converted token is mirrored, not just the px ones, so
// a theme that sets the token in another unit keeps its precedence.
function overrideDeclarations(lines, names) {
  const declarations = [];
  for (const line of lines) {
    if (line === "") {
      if (declarations.length && declarations.at(-1) !== "") {
        declarations.push("");
      }
      continue;
    }
    if (!names.has(line.name)) continue;
    const px = line.value.match(PX_VALUE);
    const value = px ? toRem(Number(px[1])) : line.value;
    declarations.push(`  ${line.name}: ${value};`);
  }
  while (declarations.at(-1) === "") declarations.pop();
  return declarations;
}

const HEADER = `/*
 * Experimental: rem units
 *
 * Generated by scripts/generate-rem-units.mjs. Don't edit it by hand.
 *
 * Redefines Salt's density-based text, size and spacing tokens in rem instead
 * of px, so the interface scales with the user's browser font size setting as
 * well as with page zoom. Hairline tokens, such as fixed sizes and borders,
 * stay in px. At the default browser font size (16px) every value resolves to
 * the same pixel size as the standard theme.
 *
 * Import after your theme stylesheets. If you also use mobile-interim.css,
 * import it after this file so its mobile values take precedence.
 */

/*
 * 1rem must resolve to the user's browser default font size. SaltProvider places
 * .salt-theme on <html>, and global.css sizes .salt-theme with the body text
 * token, which would otherwise shrink the root and compound every rem value.
 */
:root.salt-theme {
  font-size: 100%;
}

:root.salt-theme > body {
  font-size: var(--salt-text-fontSize);
}
`;

export function generateRemUnits(sourceDir = cssDir) {
  const names = convertedTokenNames(sourceDir);
  const seen = new Set();
  let output = HEADER;
  for (const [file, title] of SOURCES) {
    const css = fs.readFileSync(path.join(sourceDir, file), "utf8");
    const blocks = [];
    for (const { selectors, lines } of parseRules(css)) {
      const declarations = overrideDeclarations(lines, names);
      if (!declarations.length) continue;
      const block = `${selectors.map(overrideSelector).join(",\n")} {\n${declarations.join("\n")}\n}\n`;
      // theme-next's mobile text rule repeats the legacy one.
      if (seen.has(block)) continue;
      seen.add(block);
      blocks.push(block);
    }
    if (blocks.length) output += `\n/* ${title} */\n${blocks.join("\n")}`;
  }
  return output;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(outputPath, generateRemUnits());
  console.log(`Generated ${path.relative(process.cwd(), outputPath)}`);
}
