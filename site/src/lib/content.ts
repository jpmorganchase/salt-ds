import {
  getMdxRaw,
  getSharedConfig,
  resolveMosaicMode,
} from "@jpmorganchase/mosaic-site-middleware";
import { cache } from "react";

export function canonicalRoute(
  frontmatter: Record<string, unknown>,
  fallback: string,
): string {
  const { route } = frontmatter;
  return typeof route === "string" && /^\/(?!\/)/.test(route)
    ? route
    : fallback;
}

/** Metadata and content share the same request-cached resolution. */
export const resolveContent = cache(async (originalPathname: string) => {
  const { mode, contentUrl } = resolveMosaicMode();
  let pathname = originalPathname;

  // Folder URLs are generated by Salt navigation. Resolve their index in the
  // same request, while preserving true redirects for content that has moved.
  for (let hop = 0; hop <= 3; hop++) {
    const [content, sharedConfig] = await Promise.all([
      getMdxRaw(pathname, mode, contentUrl),
      getSharedConfig(pathname, mode, contentUrl),
    ]);
    if (content.kind !== "redirect") {
      return { content, sharedConfig, pathname };
    }
    if (content.destination !== `${pathname.replace(/\/+$/, "")}/index`) {
      return { content, sharedConfig, pathname };
    }
    pathname = content.destination;
  }

  throw new Error(`Too many content redirects for ${originalPathname}`);
});
